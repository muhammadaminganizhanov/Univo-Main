// Generates UNIVO "logo + name" lockup geometry for the web.
// Port of the Brand Book v1.2.2 kit (scripts/kit.mjs → lockupParts):
// master logo is untouched; separator at 1.75w; name in Onest SemiBold (outlined),
// caps height 1.75w, tracking 6 %, centred on the x-height.
// Official lockup files exist only for UNIVO DEV and UNIVO PRODUCTION; TECH, RETAIL
// and SLOT are built by the same rule and must be confirmed by the brand owner.
// Run: pnpm brand:lockups
import fs from "node:fs";

const here = (p) => new URL(p, import.meta.url);
const GL = JSON.parse(fs.readFileSync(here("./glyphs/onest600.json"), "utf8"));
const f = (n) => Math.round(n * 1000) / 1000;

const M = { W: 282, H: 64, top: -32, boxH: 97 };
const LK = { cap: 28, gap: 28, rule: 2.5, track: 42 };
const NAMES = ["TECH", "PRODUCTION", "RETAIL", "SLOT"];

function lockup(name) {
  let x = 0;
  const parts = [];
  for (const ch of name) {
    const gl = GL.glyphs[ch];
    if (!gl) throw new Error(`No glyph for "${ch}"`);
    if (ch !== " ") parts.push([x, gl]);
    x += gl.adv + LK.track;
  }
  const x0 = Math.min(...parts.map(([q, gl]) => q + gl.bbox[0]));
  const x1 = Math.max(...parts.map(([q, gl]) => q + gl.bbox[2]));
  const s = LK.cap / GL.cap;
  const ruleX = M.W + LK.gap;
  const textX = ruleX + LK.rule + LK.gap;
  const capTop = (M.H - LK.cap) / 2;
  return {
    width: f(textX + (x1 - x0) * s),
    ruleX,
    labelTransform: `translate(${f(textX - x0 * s)} ${f(capTop + LK.cap)}) scale(${+s.toPrecision(5)})`,
    glyphs: parts.map(([q, gl]) => ({ x: f(q), d: gl.d })),
  };
}

const data = Object.fromEntries(NAMES.map((n) => [n, lockup(n)]));
const out =
  "// AUTO-GENERATED by packages/brand/scripts/generate-lockups.mjs — do not edit by hand.\n" +
  "export const LOCKUP_GEOMETRY = " +
  JSON.stringify(data, null, 2) +
  " as const;\n";
fs.writeFileSync(here("../../src/shared/brand/lockups.generated.ts"), out);
console.warn(`lockups: ${NAMES.join(", ")} → src/lockups.generated.ts`);
